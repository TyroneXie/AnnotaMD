import { createRequire } from 'node:module'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { getIconData } from '@iconify/utils'

const require = createRequire(import.meta.url)
const collection = require('@iconify-json/mdi/icons.json')
const languages = {
  javascript: ['language-javascript', '#b08a00'],
  typescript: ['language-typescript', '#3178c6'],
  python: ['language-python', '#3776ab'],
  java: ['language-java', '#e76f00'],
  json: ['code-json', '#b07b00'],
  bash: ['console', '#439a4b'],
  sql: ['database', '#3882b5'],
  markup: ['language-html5', '#e44d26'],
  css: ['language-css3', '#1572b6'],
  yaml: ['code-braces', '#cb4040'],
  markdown: ['language-markdown', 'currentColor'],
  go: ['language-go', '#00a2b8'],
  rust: ['language-rust', 'currentColor'],
  c: ['language-c', '#6593c3'],
  cpp: ['language-cpp', '#00599c'],
  csharp: ['language-csharp', '#9b4f96'],
  kotlin: ['language-kotlin', '#9b4fe0'],
  swift: ['language-swift', '#f05138'],
  php: ['language-php', '#777bb3'],
  ruby: ['language-ruby', '#cc342d'],
  docker: ['docker', '#2496ed'],
  graphql: ['graphql', '#e535ab'],
  powershell: ['powershell', '#5391fe'],
  haskell: ['language-haskell', '#8f6bad'],
  lua: ['language-lua', '#5270bd'],
  r: ['language-r', '#276dc3'],
  fortran: ['language-fortran', '#9d5696'],
  jsx: ['language-jsx', '#b08a00'],
}

const icons = Object.fromEntries(Object.entries(languages).map(([language, [name, color]]) => {
  const icon = getIconData(collection, name)
  if (!icon) throw new Error(`Missing language icon: mdi:${name}`)
  return [language, { viewBox: `0 0 ${icon.width} ${icon.height}`, body: icon.body, color }]
}))
const output = fileURLToPath(new URL('../packages/muya/src/ui/codeBlockLanguageSelector/generatedLanguageIcons.ts', import.meta.url))
await writeFile(output,
  '// Generated by node scripts/generateLanguageIcons.mjs.\n'
  + '// Material Design Icons by Pictogrammers, Apache-2.0.\n'
  + '// https://github.com/Templarian/MaterialDesign\n'
  + 'export const LANGUAGE_ICONS: Record<string, { viewBox: string; body: string; color: string }> = '
  + JSON.stringify(icons, null, 4) + ';\n'
)
