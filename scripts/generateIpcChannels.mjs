import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const require = createRequire(new URL('../packages/desktop/package.json', import.meta.url))
const ts = require('typescript')
const source = await readFile(new URL('../packages/desktop/src/shared/types/ipc.ts', import.meta.url), 'utf8')
const syntax = ts.createSourceFile('ipc.ts', source, ts.ScriptTarget.Latest, true)
const interfaces = {
  INVOKE_CHANNELS: 'IpcInvokeChannels',
  SEND_CHANNELS: 'IpcSendChannels',
  SYNC_CHANNELS: 'IpcSyncChannels',
  EVENT_CHANNELS: 'IpcMainEventChannels'
}
const chunks = [
  '// Generated by scripts/generateIpcChannels.mjs. Do not edit by hand.',
  `import type { ${Object.values(interfaces).join(', ')} } from './types/ipc'`, ''
]
for (const [constant, name] of Object.entries(interfaces)) {
  const declaration = syntax.statements.find(node => ts.isInterfaceDeclaration(node) && node.name.text === name)
  if (!declaration) throw new Error(`Missing IPC contract ${name}`)
  const names = declaration.members.filter(node => node.name && ts.isStringLiteral(node.name))
    .map(node => node.name.text)
    .filter(value => constant !== 'SEND_CHANNELS' || value.startsWith('annotamd::'))
  if (!names.length || names.some(value => !/^[\w:-]+$/.test(value))) throw new Error(`Invalid channels in ${name}`)
  chunks.push(`export const ${constant}: ReadonlySet<string> = new Set([`,
    ...names.map(value => `  '${value}',`), `] satisfies (keyof ${name})[])`, '')
}
const destination = fileURLToPath(new URL('../packages/desktop/src/shared/ipcChannels.ts', import.meta.url))
const generated = chunks.join('\n')
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== generated) throw new Error('IPC channel list is stale. Run node scripts/generateIpcChannels.mjs')
} else {
  await writeFile(destination, generated)
}
